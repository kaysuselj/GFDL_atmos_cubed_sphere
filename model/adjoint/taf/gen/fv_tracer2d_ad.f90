            call fv_tp_2d_tl( q(isd,jsd,k,iq),q_tl(isd,jsd,k,iq),cx(is,jsd,k),cy(isd,js,k),npx,npy,hord,fx,fx_tl,fy,fy_tl,xfx(is,jsd,k),yfx(isd,js,k),gridstruct,bd,ra_x,ra_y,lim_fac,mfx=mfx(is,js,k),mfy=mfy(is,js,k),mass=dp1(isd,jsd,k),nord=nord_tr,damp_c=trdm )
          else
            call fv_tp_2d_tl( q(isd,jsd,k,iq),q_tl(isd,jsd,k,iq),cx(is,jsd,k),cy(isd,js,k),npx,npy,hord,fx,fx_tl,fy,fy_tl,xfx(is,jsd,k),yfx(isd,js,k),gridstruct,bd,ra_x,ra_y,lim_fac,mfx=mfx(is,js,k),mfy=mfy(is,js,k) )
          endif
          do j = js, je
            do i = is, ie
              q_tl(i,j,k,iq) = (-(fx_tl(i+1,j)*(rarea(i,j)/dp2(i,j))))+fx_tl(i,j)*(rarea(i,j)/dp2(i,j))-fy_tl(i,j+1)*(rarea(i,j)/dp2(i,j))+fy_tl(i,j)*(rarea(i,j)/dp2(i,j))+q_tl(i,j,k,iq)*(dp1(i,j,k)/dp2(i,j))
              q(i,j,k,iq) = (q(i,j,k,iq)*dp1(i,j,k)+(fx(i,j)-fx(i+1,j)+(fy(i,j)-fy(i,j+1)))*rarea(i,j))/dp2(i,j)
            end do
          end do
        end do
        if (it /= ksplt(k)) then
          do j = js, je
            do i = is, ie
              dp1(i,j,k) = dp2(i,j)
            end do
          end do
        else
          if (present(dpa)) then
            dpa(:,:,k) = dp2
          endif
        endif
      endif
    end do
    if (it /= nsplt) then
      call start_group_halo_update_tl( q_pack,q,q_tl,domain )
    endif
  end do

  end subroutine tracer_2d_tl
