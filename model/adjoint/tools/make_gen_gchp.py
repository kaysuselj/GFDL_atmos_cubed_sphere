#!/usr/bin/env python3
"""Write taf/gen_gchp/: the TAF output of taf/gen/ with all module names that would clash in GCHP
renamed (stub modules -> stb_*, the forward modules tp_core_mod, fv_tracer2d_mod, fv_mapz_mod,
fv_fill_mod -> adj_*). GCHP compiles these files as they are (no preprocessor renaming, which
depends on the compiler); the standalone builds use the same names through -D (Makefile RENAME).
usage: make_gen_gchp.py <taf/gen> <taf/gen_gchp>"""
import os, re, sys

STUBS = ['platform_mod', 'constants_mod', 'field_manager_mod', 'tracer_manager_mod', 'fv_timing_mod',
         'mpp_mod', 'mpp_domains_mod', 'fv_mp_mod', 'fv_arrays_mod', 'boundary_mod', 'fv_grid_utils_mod',
         'fv_cmp_mod']
FWD = ['tp_core_mod', 'fv_tracer2d_mod', 'fv_mapz_mod', 'fv_fill_mod']
NAMES = {**{m: 'stb_' + m for m in STUBS}, **{m: 'adj_' + m for m in FWD}}
pat = re.compile(r'(?i)\b(' + '|'.join(NAMES) + r')\b')

MAXLEN = 120


def wrap(line):
    """free-form lines longer than MAXLEN: continuation with '&' at the end and at the start of the
    next line (allowed anywhere outside strings, also inside a token); comments are split"""
    if len(line) <= 132:
        return [line]
    s = line.lstrip()
    if s.startswith('!'):
        ind = line[:len(line) - len(s)]
        body = s.lstrip('!').strip()
        out = []
        while body:
            out.append(ind + '! ' + body[:MAXLEN - len(ind) - 2])
            body = body[MAXLEN - len(ind) - 2:]
        return out
    out, rest = [], line
    while len(rest) > MAXLEN:
        cut, q = None, None
        for i, ch in enumerate(rest[:MAXLEN]):
            if q:
                if ch == q:
                    q = None
                continue
            if ch in "'\"":
                q = ch
                continue
            if ch in ', ()+-*/=' and i > 40:
                cut = i + 1
        assert cut is not None and q is None, line[:80]
        out.append(rest[:cut] + '&')
        rest = '&' + rest[cut:]
    out.append(rest)
    return out


src, dst = sys.argv[1], sys.argv[2]
os.makedirs(dst, exist_ok=True)
for f in sorted(os.listdir(src)):
    if not f.endswith('_ad.f90'):
        continue
    t = open(os.path.join(src, f)).read()
    out = []
    for line in t.split('\n'):
        if line.lstrip().startswith('!'):
            out.append(line)                     # comments unchanged
            continue
        # leave string literals alone
        parts = re.split(r"('[^']*'|\"[^\"]*\")", line)
        out.append(''.join(p if i % 2 else pat.sub(lambda m: NAMES[m.group(1).lower()], p)
                           for i, p in enumerate(parts)))
    out = [w for l in out for w in wrap(l)]
    hdr = ('! Generated by tools/make_gen_gchp.py from taf/gen/' + f + ': module names renamed for\n'
           '! the GCHP build (stb_*, adj_*), lines wrapped at 132 columns. Do not edit.\n')
    open(os.path.join(dst, f.replace('_ad.f90', '_ad_gchp.F90')), 'w').write(hdr + '\n'.join(out))
print('wrote', dst)
